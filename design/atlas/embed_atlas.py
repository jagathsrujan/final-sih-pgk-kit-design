#!/usr/bin/env python3
"""Inline an architecture-atlas sheet into deck.html, between its marker pair.

    python3 embed_atlas.py --inline ../../submission/deck/deck.html

The deck is a single self-contained file that prints to PDF with no external
assets, so the sheet is inlined as SVG rather than linked.  SVG and not PNG
because the deck is printed to PDF: vector stays sharp at whatever the print
path rasterises to, and the text in it is the deck's own text, not a picture
of text.

This is the atlas counterpart of `submission/deck/figures/embed_cad.py` and
uses the same marker convention:

    <!-- ATLAS:<slot>:start -->   ... <figure> ...   <!-- ATLAS:<slot>:end -->

Captions follow the deck's tone rules: no criterion IDs, and no number that is
still unruled in design/07-cad-evidence.md or design/08-atlas.md.  The sheet
itself carries the numbers; the caption only says how to read it.
"""

import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")

# slot -> (sheet id, caption)
SLOTS = {
    # Slide 3 - Technical Approach.  The template asks for "Methodology and
    # process for implementation (Flow Charts/Images)", which is this sheet.
    # Superseded `sheet1` (a swimlane grid) on 2026-09-21: the grid showed what
    # exists but not what is wired to what.  sheet1 stays in the review set.
    "s3-atlas": (
        "flow",
        "Every block is wired to the block it actually talks to, and the table "
        "below says which of them is acting in each phase of the flight. The "
        "criterion behind each block is named in the file rather than on the "
        "slide, and the dashed blocks and connectors are the ones carried from "
        "the reference work rather than ours.",
    ),
}


def slot_html(slot):
    sheet_id, caption = SLOTS[slot]
    path = os.path.join(OUT, sheet_id + ".svg")
    with open(path, encoding="utf-8") as fh:
        svg = fh.read().strip()

    # The deck's own rule is that an inlined figure emits no <style> element, so
    # that it cannot leak rules into the slide.  render_svg.py already complies;
    # assert it here so a future renderer change cannot quietly break the deck.
    if "<style" in svg:
        raise SystemExit("%s contains a <style> element; the deck forbids it"
                         % path)
    if not svg.startswith("<svg"):
        raise SystemExit("%s does not start with <svg" % path)

    return ('    <figure class="atlas">\n'
            "      <!-- %s - generated by design/atlas/render_svg.py -->\n"
            "      %s\n"
            "      <figcaption>%s</figcaption>\n"
            "    </figure>" % (sheet_id, svg.replace("\n", "\n      "),
                              caption))


def inline(deck_path, slots):
    with open(deck_path, encoding="utf-8") as fh:
        doc = fh.read()
    for slot in slots:
        pat = re.compile(r"(<!-- ATLAS:%s:start -->)(.*?)(<!-- ATLAS:%s:end -->)"
                         % (slot, slot), re.S)
        if not pat.search(doc):
            raise SystemExit("marker pair for %s not found in %s"
                             % (slot, deck_path))
        body = slot_html(slot)
        doc = pat.sub(lambda m: "\n".join([m.group(1), body, m.group(3)]), doc)
        print("   inlined %-12s from out/%s.svg" % (slot, SLOTS[slot][0]))
    with open(deck_path, "w", encoding="utf-8") as fh:
        fh.write(doc)
    print("wrote %s (%.1f kB)" % (deck_path, os.path.getsize(deck_path) / 1e3))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--inline", metavar="DECK_HTML", required=True)
    ap.add_argument("--slot", action="append",
                    help="limit to one slot (repeatable); default all")
    a = ap.parse_args()
    inline(os.path.abspath(a.inline), a.slot or list(SLOTS))
